#!/usr/bin/env python3
"""otfautohint 용 fontinfo 생성 — Source Han Sans(Noto Sans KR)가 쓴 방식과 같이
라틴과 한글에 서로 다른 얼라인먼트 존/스템 폭(FDDict)을 준다.
한글 존은 글리프 실측(상단 평탄선 피크, 받침 하단 피크, ㅡ/ㅣ 스템 폭)에서 잡는다."""
import sys, os, collections, random
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen

def measure(path):
    f = TTFont(path); gs = f.getGlyphSet(); cmap = f.getBestCmap()
    pd = f["CFF "].cff.topDictIndex[0].FDArray[0].Private
    def bounds(u):
        bp = BoundsPen(gs); gs[cmap[u]].draw(bp); return [round(v) for v in bp.bounds]
    hs = bounds(0x3161); vs = bounds(0x3163)                      # ㅡ, ㅣ
    random.seed(1)
    syl = [u for u in range(0xAC00, 0xD7A4) if u in cmap]
    top = collections.Counter(); bot = collections.Counter()
    for u in random.sample(syl, 3000):
        x0, y0, x1, y1 = bounds(u); top[y1] += 1; bot[y0] += 1
    # 상단: 최빈값 2개(평탄선/살짝 위) → 존 = [min, max]
    t = sorted(v for v, _ in top.most_common(2)); b = sorted(v for v, _ in bot.most_common(4))
    hangul = dict(top=t[0], top_over=max(t[1] - t[0], 6), base=b[-1], base_over=min(b[0] - b[-1], -6),
                  H=hs[3] - hs[1], V=vs[2] - vs[0])
    bv = pd.BlueValues
    latin = dict(base=bv[1], base_over=bv[0] - bv[1], lc=bv[2], lc_over=bv[3] - bv[2], cap=bv[4], cap_over=bv[5] - bv[4],
                 H=pd.StdHW, V=pd.StdVW)
    names = f.getGlyphOrder()
    hg = sorted({cmap[u] for u in list(range(0x1100, 0x1200)) + list(range(0x3131, 0x3164)) + list(range(0xAC00, 0xD7A4)) if u in cmap})
    return hangul, latin, hg, names

def cid_regexes(cids):
    """연속된 cid 이름 목록을 정규식 몇 개로 압축"""
    nums = sorted(int(c[3:]) for c in cids); out = []
    start = prev = nums[0]
    def emit(a, b): out.append(f"^cid({'|'.join(str(n).zfill(5) for n in range(a, b + 1))})$") if b - a < 40 else None
    ranges = []
    for n in nums[1:]:
        if n != prev + 1: ranges.append((start, prev)); start = n
        prev = n
    ranges.append((start, prev))
    return ranges

def range_regex(a, b):
    """a..b (5자리 cid 번호) 를 매칭하는 정규식들 — 십진 자릿수 분해"""
    res = []
    while a <= b:
        # a 에서 시작해 가능한 가장 큰 10^k 블록
        k = 0
        while k < 5 and a % (10 ** (k + 1)) == 0 and a + 10 ** (k + 1) - 1 <= b: k += 1
        end = a + 10 ** k - 1
        s = str(a).zfill(5)
        res.append("^cid" + s[:5 - k] + "[0-9]" * k + "$" if k else "^cid" + s + "$")
        a = end + 1
    return res

def write(path_font, out):
    hangul, latin, hg, names = measure(path_font)
    hnums = sorted(int(n[3:]) for n in hg); hset = set(hnums)
    other = [int(n[3:]) for n in names if n.startswith("cid") and int(n[3:]) not in hset]
    def to_ranges(nums):
        nums = sorted(nums); r = []; s = p = nums[0]
        for n in nums[1:]:
            if n != p + 1: r.append((s, p)); s = n
            p = n
        r.append((s, p)); return r
    L = []
    L.append(f"""# generated by make_fontinfo.py from {os.path.basename(path_font)}
begin FDDict Latin
    OrigEmSqUnits 2048
    FlexOK true
    FontName {os.path.basename(path_font).split('.')[0]}-Latin
    BaselineYCoord {latin['base']}
    BaselineOvershoot {latin['base_over']}
    LcHeight {latin['lc']}
    LcOvershoot {latin['lc_over']}
    CapHeight {latin['cap']}
    CapOvershoot {latin['cap_over']}
    DominantH [{latin['H']}]
    DominantV [{latin['V']}]
end FDDict Latin

begin FDDict Hangul
    OrigEmSqUnits 2048
    FlexOK true
    FontName {os.path.basename(path_font).split('.')[0]}-Hangul
    BaselineYCoord {hangul['base']}
    BaselineOvershoot {hangul['base_over']}
    CapHeight {hangul['top']}
    CapOvershoot {hangul['top_over']}
    DominantH [{hangul['H']}]
    DominantV [{hangul['V']}]
end FDDict Hangul
""")
    for name, nums in (("Hangul", hnums), ("Latin", other)):
        regs = []
        for a, b in to_ranges(nums): regs += range_regex(a, b)
        L.append(f"begin GlyphSet {name}\n    " + "\n    ".join(regs) + f"\nend GlyphSet {name}\n")
    open(out, "w").write("\n".join(L))
    print(os.path.basename(path_font), "hangul", hangul, "| latin", latin, "| hangul glyphs", len(hnums))

if __name__ == "__main__":
    write(sys.argv[1], sys.argv[2])
